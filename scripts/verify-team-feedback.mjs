import { build } from 'esbuild'
import { chromium } from 'playwright'
import assert from 'node:assert/strict'

await build({ entryPoints: ['tests/browser/team-feedback-harness.tsx'], outfile: '.tmp/team-feedback.js', bundle: true, format: 'iife', jsx: 'automatic', define: { 'import.meta.env': '{}', 'process.env.NODE_ENV': '"test"' } })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 780 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', route => route.fulfill({ contentType: 'text/html', body: '<html><head></head><body><div id="root"></div></body></html>' }))
  await page.goto('https://team-feedback.invalid/')
  await page.addStyleTag({ content: ':root{--bg-0:#fff;--bg-1:#f8fafb;--bg-2:#f1f3f5;--border:#e2e5e9;--text-1:#202329;--text-2:#495261;--text-3:#7d8591;--blue:#3574ff;--blue-light:#edf4ff;--red:#d64040}body{margin:0;font:14px sans-serif;background:var(--bg-1)}nav{display:flex;gap:8px;flex-wrap:wrap;padding:10px} @keyframes spin{to{transform:rotate(360deg)}}' })
  await page.addStyleTag({ path: '.tmp/team-feedback.css' })
  await page.addScriptTag({ path: '.tmp/team-feedback.js' })
  const click = name => page.getByRole('button', { name, exact: true }).click()
  const replies = page.locator('.conversation-message:not(.is-human)')
  const footer = replies.first().locator('.turn-stats-footer')
  await click('发送')
  await footer.waitFor()
  assert.equal(await replies.count(), 1)
  assert.match(await replies.first().innerText(), /正在准备 Agent/)
  assert.equal(await replies.first().locator('.conversation-bubble .turn-stats-footer').count(), 0)
  assert.equal(await replies.first().locator('.conversation-streaming-label svg').count(), 1)
  await click('隐藏阶段')
  assert.equal(await replies.count(), 1)
  await click('准备')
  assert.match(await replies.first().locator('.conversation-bubble').innerText(), /执行过程/)
  await page.waitForFunction(() => /[1-9]\d*s/.test(document.querySelector('.turn-stats-footer')?.textContent || ''))
  await click('切换')
  await click('切换')
  await footer.waitFor()
  assert.notEqual(await footer.innerText(), '0s')
  await click('思考')
  assert.equal(await replies.count(), 1)
  await click('成员')
  assert.equal(await replies.count(), 2)
  await click('回复')
  await click('完成')
  await page.getByText('输入', { exact: false }).first().waitFor()
  const finished = replies.filter({ hasText: '12.0k' })
  assert.equal(await finished.count(), 1)
  assert.match(await finished.innerText(), /350/)
  assert.equal(await finished.locator('.conversation-streaming-label').count(), 0)
  const geometry = await finished.evaluate(element => {
    const bubble = element.querySelector('.conversation-bubble').getBoundingClientRect()
    const stats = element.querySelector('.turn-stats-footer').getBoundingClientRect()
    return { left: stats.left - bubble.left, gap: stats.top - bubble.bottom }
  })
  assert.equal(geometry.left, 0)
  assert.equal(geometry.gap, 6)
  await page.screenshot({ path: '.tmp/team-feedback-desktop.png' })
  await page.setViewportSize({ width: 480, height: 760 })
  await page.screenshot({ path: '.tmp/team-feedback-narrow.png' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await click('清空')
  await click('发送')
  await click('拒绝')
  assert.equal(await replies.count(), 0)
  await click('发送')
  await click('取消')
  assert.equal(await page.locator('.conversation-streaming-label').count(), 0)
  assert.deepEqual(errors, [])
  process.stdout.write('PASS: pending and lifecycle feedback, elapsed clock, remount, concurrent members, completed usage, footer alignment, narrow layout, rejection/cancellation\n')
} finally { await browser.close() }
